class FakeClient:
    def __init__(self, frames):
        self.frames = frames      # 每次 observe 依次吐一帧
        self.n = 0
        self.clicks = []
    def attach(self, w): pass
    def type(self, text): pass
    def observe(self, out, ocr=False):
        frame = self.frames[min(self.n, len(self.frames)-1)]
        self.n += 1
        return {"texts": frame}
    def click(self, x, y):
        self.clicks.append((x, y))

def run(label, frames, want_point, want_msg_part, name=None):
    fake = FakeClient(frames)
    T._ui_client = lambda: fake
    T._log = lambda *a, **k: None
    msg = T.tool_ui_search_contact("微信", name or label)
    hit = fake.clicks[-1] if fake.clicks else None
    ok = (hit is not None and hit == want_point) and (want_msg_part in msg)
    print(f"[{'PASS' if ok else 'FAIL'}] {label}: 点击 {hit} (期望 {want_point}) | 返回含「{want_msg_part}」"
          + (f" | 返回: {msg[:60]}" if not ok else ""))
    return ok

